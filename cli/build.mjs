// Bundles the CLI into one dependency-free file and copies it into the plugins, which are installed
// straight from the repository with no build step. CI rebuilds and fails if the committed copies
// differ (`git diff --exit-code`).
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const { version } = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));
const out = join(here, "dist", "code-alarm.mjs");

await build({
  entryPoints: [join(here, "src", "main.ts")],
  outfile: out,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify: false,
  legalComments: "none",
  banner: { js: "#!/usr/bin/env node\n// code-alarm, MIT License, https://github.com/Draganoider/code-alarm. Generated by cli/build.mjs: do not edit." },
  define: { __VERSION__: JSON.stringify(version) },
});

const plugin = join(here, "..", "plugins", "claude-code");
mkdirSync(join(plugin, "bin"), { recursive: true });
copyFileSync(out, join(plugin, "bin", "code-alarm.mjs"));

// The plugin's skill comes from the same source as the one `code-alarm install codex` writes. In
// the plugin, `code-alarm` is on the PATH (the plugin's bin/), so the commands are bare.
const skill = execFileSync(process.execPath, [out, "__skill", "code-alarm", "alarm"], { encoding: "utf8" });
mkdirSync(join(plugin, "skills", "alarm"), { recursive: true });
writeFileSync(join(plugin, "skills", "alarm", "SKILL.md"), skill);

console.log(`built code-alarm ${version}: cli/dist/, plugins/claude-code/bin/ and its skill`);
